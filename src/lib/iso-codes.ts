/** World Bank ISO3 코드를 경계 feature id(M49)로 변환한다. 없으면 null. */
export function isoAlpha3ToM49(alpha3: string | null): string | null {
  if (typeof alpha3 !== "string") return null;
  const code = alpha3.trim().toUpperCase();
  if (!code) return null;
  return ISO_ALPHA3_TO_M49[code] ?? null;
}
